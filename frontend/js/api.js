/* api.js — all backend calls in one place */

// Resolve the API base dynamically from the current origin so local dev,
// Cloudflare tunnels, and production all work without editing this file.
// scripts/inject-tunnel.py may override CLIMATEINSIGHT_CONFIG.apiBase at
// deploy time (e.g. "https://your-tunnel.trycloudflare.com/api").
function resolveApiBase() {
  const configured = window.CLIMATEINSIGHT_CONFIG?.apiBase?.trim();
  if (configured) {
    const base = configured.replace(/\/+$/, "");
    return base.endsWith("/api") ? base : `${base}/api`;
  }
  // When opened as file:// (e.g. directly from Finder), fall back to localhost:5001
  if (window.location.protocol === "file:") {
    return "http://localhost:5001/api";
  }
  const base = window.location.origin.replace(/\/+$/, "");
  return base.endsWith("/api") ? base : `${base}/api`;
}

const API_BASE = resolveApiBase();
const apiLogs = [];

function logRequest(method, url, status) {
  apiLogs.push({
    timestamp: new Date().toLocaleTimeString(),
    method,
    url,
    status
  });
  if (apiLogs.length > 50) apiLogs.shift();
  document.dispatchEvent(new CustomEvent("api-log-updated"));
}

const Api = {
  getLogs() {
    return apiLogs;
  },

  async health() {
    try {
      const res = await fetch(`${API_BASE}/health`);
      logRequest("GET", "/health", res.status);
      return res.ok;
    } catch (err) {
      logRequest("GET", "/health", "FAILED");
      throw err;
    }
  },

  async chat(question, sessionId) {
    try {
      const res = await fetch(`${API_BASE}/chat`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ question, session_id: sessionId }),
      });
      logRequest("POST", "/chat", res.status);
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "Request failed");
      return data; // { answer, citations, session_id }
    } catch (err) {
      if (err.message !== "Request failed") {
        logRequest("POST", "/chat", "FAILED");
      }
      throw err;
    }
  },

  /**
   * Generate a Mermaid concept graph + explanation for a climate question.
   *
   * Grounded in the retrieved IPCC / paper passages; generated by the local
   * Ollama model (falls back to a map of the retrieved sources).
   *
   * @param  {string} question
   * @returns {{ explanation: string, mermaid: string, source: string }}
   */
  async conceptGraph(question) {
    try {
      const res = await fetch(`${API_BASE}/concept-graph`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ question }),
      });
      logRequest("POST", "/concept-graph", res.status);
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "concept-graph request failed");
      return data; // { explanation, mermaid, source, sources, citations }
    } catch (err) {
      if (err.message !== "concept-graph request failed") {
        logRequest("POST", "/concept-graph", "FAILED");
      }
      throw err;
    }
  },

  async clearSession(sessionId) {
    if (!sessionId) return;
    try {
      const res = await fetch(`${API_BASE}/session/${sessionId}`, { method: "DELETE" });
      logRequest("DELETE", `/session/${sessionId}`, res.status);
    } catch (err) {
      logRequest("DELETE", `/session/${sessionId}`, "FAILED");
    }
  },
};