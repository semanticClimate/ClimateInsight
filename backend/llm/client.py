"""
client.py
---------
Handles communication with the LLM backend.

ClimateInsight is fully open source and runs locally: every answer is
generated by an open-weight model served by Ollama (MIT licence,
https://github.com/ollama/ollama). No hosted or proprietary API is used.

Config (env vars):
    OLLAMA_BASE_URL  default http://localhost:11434
    OLLAMA_MODEL     default llama3.2:latest   (Llama 3.2 Community Licence)
    OLLAMA_TIMEOUT   default 120 seconds
"""

import os

import requests

OLLAMA_BASE = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434").rstrip("/")
OLLAMA_URL = f"{OLLAMA_BASE}/api/generate"
OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "llama3.2:latest")
OLLAMA_TIMEOUT = int(os.getenv("OLLAMA_TIMEOUT", "120"))


def ask_llm(
    prompt: str,
    temperature: float = 0.2,
    max_tokens: int = 1024,
    json_mode: bool = False,
) -> str:
    """
    Send a prompt to the local Ollama model and return the response text.

    json_mode=True asks Ollama to constrain output to valid JSON.

    Raises RuntimeError with a user-readable message if Ollama is
    unreachable, times out, or returns an error.
    """
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": temperature,
            "num_predict": max_tokens,
        },
    }
    if json_mode:
        payload["format"] = "json"

    try:
        response = requests.post(OLLAMA_URL, json=payload, timeout=OLLAMA_TIMEOUT)
        if response.status_code == 404:
            raise RuntimeError(
                f"Ollama model '{OLLAMA_MODEL}' is not installed. "
                f"Run: ollama pull {OLLAMA_MODEL}"
            )
        response.raise_for_status()
        return response.json().get("response", "").strip()

    except requests.exceptions.ConnectionError:
        raise RuntimeError("Cannot connect to Ollama. Is 'ollama serve' running?")
    except requests.exceptions.Timeout:
        raise RuntimeError("Ollama timed out. Try a smaller model or increase OLLAMA_TIMEOUT.")
    except requests.exceptions.HTTPError as e:
        raise RuntimeError(f"Ollama request failed: {response.status_code}") from e


# Keep the old name as an alias so nothing else breaks
ask_ollama = ask_llm
